# =========================================================
# SEARCH KNOWLEDGE
# =========================================================

def search_knowledge(query):

    query_lower = query.lower()

    query_words = set(
        query_lower
        .replace(",", " ")
        .replace(".", " ")
        .replace("?", " ")
        .replace("!", " ")
        .split()
    )

    stop_words = {
        "i", "my", "me", "the", "a", "an",
        "is", "are", "was", "were", "to",
        "and", "or", "of", "in", "on",
        "for", "with", "this", "that",
        "it", "please", "can", "you",
        "help", "have", "has", "been",
        "but", "still", "need", "want",
        "there", "how", "do"
    }

    query_words = {
        word
        for word in query_words
        if word not in stop_words
    }

    scored_results = []

    for article in knowledge_base:

        score = 0

        title = article["title"].lower()
        category = article["category"].lower()

        keywords = {
            keyword.lower()
            for keyword in article.get("keywords", [])
        }

        content_words = set(
            article["content"].lower()
            .replace(",", " ")
            .replace(".", " ")
            .split()
        )

        # Exact keyword matching
        for keyword in keywords:

            if keyword in query_lower:
                score += 15

        # Title matching
        title_words = set(title.split())

        score += len(
            query_words & title_words
        ) * 8

        # Category matching
        category_words = set(category.split())

        score += len(
            query_words & category_words
        ) * 5

        # Content matching
        score += len(
            query_words & content_words
        ) * 1

        if score > 0:

            scored_results.append(
                (score, article)
            )

    scored_results.sort(
        key=lambda x: x[0],
        reverse=True
    )

    # Only return genuinely relevant articles.
    # This prevents unrelated articles such as VPN
    # instructions from being returned for TV problems.
    if not scored_results:
        return []

    best_score = scored_results[0][0]

    if best_score < 15:
        return []

    # Only keep articles close to the best match.
    relevant_results = [
        article
        for score, article in scored_results[:3]
        if score >= max(15, best_score * 0.50)
    ]

    return relevant_results